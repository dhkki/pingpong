    #      지령   0.0 = 테이블 왼쪽 사이드라인 = 프로그램 시작·종료 위치
    #      지령  24.2 = 하한, 힌지가 ROI 좌측 끝에서 130mm 왼쪽 (X -511)
    #      지령  36.8 = ROI 좌측 끝                          (X -381)
    #      지령  49.9 = 대기 자세, 라켓이 센터라인            (X -245)
    #      지령 110.3 = 상한, 힌지가 ROI 우측 끝              (X +381)
    #
    #  ★ 시작·종료 위치(0)는 이 범위 밖이다 ★
    #    역기구학은 24.2~110.3 안에서만 해를 내지만, 시작·복귀는 이 클램프를
    #    거치지 않고 직접 지령하므로 사이드라인까지 그대로 간다.
    linear_min_cmd: float = 24.2
    linear_max_cmd: float = 86.0

    #  ★ 실측 필요 ★
    #  theta=0 (막대 수직), 리니어 지령 0 일 때 **막대 끝(손목 축)** 의 X(mm).
    #  라켓 중심이 아니라 손목 축이라는 점에 주의.  라켓 중심까지는 아래
    #  paddle_offset_mm 이 따로 더해진다.
    #  ★ 2026-08-12 실측 ★
    #  지령 0 에서 막대의 바닥 교점(힌지)의 테이블 X.
    #  ★ DLL 은 프로그램을 켤 때 캐리지가 있던 자리를 0 으로 잡는다 ★
    #    그래서 시작 위치가 곧 원점이다.  음수 지령을 쓰지 않도록 시작
    #    위치를 테이블 왼쪽 사이드라인에 맞춘다.
    #      테이블 폭 1525mm -> 사이드라인은 X = -762.5
    arm_x_offset_mm: float = -762.5

    #  ★ 손목 축(모터 5) -> 라켓 중심 ★
    #  모터 5 가 막대의 기울기를 상쇄해 라켓을 **항상 수평**으로 유지하므로,
    #  이 130mm 구간은 각도와 무관하게 늘 수평이다.  따라서 높이(Z)에는
    #  기여하지 않고 폭 방향(X)에만 상수로 더해진다.
    #  방향: 로봇이 사람을 바라볼 때 로봇 기준 오른쪽.
    #  X 축이 반대로 잡혀 있으면 음수로 넣는다.
    paddle_offset_mm: float = 130.0

    #  막대에 수직인 성분.  모터 5 보정이 완전하면 0 이다.
    #  눕힐수록 라켓이 처지는 것이 확인되면 그만큼 넣는다.
    paddle_perp_mm: float = 0.0

    #  theta 음수(우측)가 X 의 + 인지 - 인지.
    arm_x_sign: float = 1.0

    # --- 라켓 ---
    blade_radius_mm: float = 100.0      # 블레이드 반경
    blade_usable_frac: float = 0.7      # 이 비율 안의 오차는 감수한다

    # --- 스윙 반경 하한 ---
    #  0 = 제한 없음. theta 0(수직)까지 그대로 쓴다.
    min_swing_radius_mm: float = 0.0


